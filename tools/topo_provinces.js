// Step 3 of the province build: province features -> a simplified topology (lib/provinces.js)
// and the province table (provinces.js: names, areas, centres, neighbours with border km).
// usage: node tools/topo_provinces.js FEATURES.json META.json [minWeight in deg^2]
const fs = require('fs'), path = require('path');
const { topology } = require('./node_modules/topojson-server');
const { presimplify, simplify, filter, filterWeight } = require('./node_modules/topojson-simplify');
const { quantize } = require('./node_modules/topojson-client');
const fc = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const meta = JSON.parse(fs.readFileSync(process.argv[3], 'utf8'));
const minW = +(process.argv[4] || 0.05);           // smallest triangle kept, in square degrees
let topo = topology({ provinces: fc });
topo = presimplify(topo);
topo = simplify(topo, minW);
topo = filter(topo, filterWeight(topo, minW));           // drop slivers the simplification squashed (they can flip inside out)
topo = quantize(topo, 2e4);
const root = path.join(__dirname, '..');
fs.writeFileSync(path.join(root, 'lib', 'provinces.js'), 'window.PROVTOPO=' + JSON.stringify(topo) + ';\n');
fs.writeFileSync(path.join(root, 'provinces.js'), '// Generated by tools/build_provinces.sh - do not edit. id, key (country), name, km2, centre [lon,lat], nb {id: shared border km}\n(typeof window !== "undefined" ? window : globalThis).CWPROV=' + JSON.stringify(meta) + ';\n');
console.log('topology', (fs.statSync(path.join(root, 'lib', 'provinces.js')).size / 1024).toFixed(0) + ' KB', 'table', (fs.statSync(path.join(root, 'provinces.js')).size / 1024).toFixed(0) + ' KB');
