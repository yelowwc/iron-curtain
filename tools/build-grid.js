// node tools/build-grid.js - writes provgrid.js: the world as half-degree cells, each with the province it lies in.
// Wars are fought on these cells (divisions move freely, the front runs through them). Run again if the provinces change.
globalThis.window = globalThis;
require('../lib/provinces.js');
const d3 = require('../lib/d3.min.js'), tj = require('../lib/topojson-client.min.js'), fs = require('fs');
const STEP = 0.5, LON0 = -180, LAT0 = 84, COLS = 720, ROWS = 280;          // rows from 84N down to 56S
const feats = tj.feature(PROVTOPO, PROVTOPO.objects.provinces).features;
const grid = new Int16Array(COLS * ROWS).fill(-1);
const t0 = Date.now();
for (const f of feats) {
  const id = +f.id;
  const [[x0, y0], [x1, y1]] = d3.geoBounds(f);
  const lonRanges = x0 <= x1 ? [[x0, x1]] : [[x0, 180], [-180, x1]];         // a province across the date line
  const r0 = Math.max(0, Math.floor((LAT0 - y1) / STEP)), r1 = Math.min(ROWS - 1, Math.floor((LAT0 - y0) / STEP));
  let n = 0;
  for (const [a, b] of lonRanges) {
    const c0 = Math.max(0, Math.floor((a - LON0) / STEP)), c1 = Math.min(COLS - 1, Math.floor((b - LON0) / STEP));
    for (let r = r0; r <= r1; r++) for (let c = c0; c <= c1; c++) {
      const pt = [LON0 + (c + 0.5) * STEP, LAT0 - (r + 0.5) * STEP];
      if (d3.geoContains(f, pt)) { grid[r * COLS + c] = id; n++; }
    }
  }
  // a province too small to hold a cell centre still gets the cell of its middle
  if (!n) { const [lon, lat] = d3.geoCentroid(f); const c = Math.floor((lon - LON0) / STEP), r = Math.floor((LAT0 - lat) / STEP); if (r >= 0 && r < ROWS && c >= 0 && c < COLS) grid[r * COLS + c] = id; }
}
// run-length code: value+1 in base 36, then the run length
const runs = [];
for (let i = 0; i < grid.length;) { let j = i; while (j < grid.length && grid[j] === grid[i]) j++; runs.push((grid[i] + 1).toString(36) + '.' + (j - i).toString(36)); i = j; }
const out = `// Generated by tools/build-grid.js - do not edit. Half-degree cells (720 x 280, from 180W 84N), each the id of its province or -1 (sea).
(typeof window !== "undefined" ? window : globalThis).CWGRID={step:${STEP},lon0:${LON0},lat0:${LAT0},cols:${COLS},rows:${ROWS},rle:"${runs.join(',')}"};
`;
fs.writeFileSync(__dirname + '/../provgrid.js', out);
const land = grid.filter(v => v >= 0).length, cover = new Set(grid).size - 1;
console.log(`provgrid.js: ${land} land cells, ${cover} of ${feats.length} provinces, ${(out.length / 1024).toFixed(0)} KB, ${((Date.now() - t0) / 1000).toFixed(1)} s`);
